class ProtocolTest {

    /** Vectors generated by pysrp configured for csrp/owntone semantics (see srp_vectors.txt). */
    @Test
    fun srpMatchesReferenceImplementation() {
        val v = javaClass.classLoader!!.getResource("srp_vectors.txt")!!.readText().lines()
            .filter { it.isNotBlank() }.associate { it.substringBefore(' ') to it.substringAfter(' ').hexToBytes() }
        val client = SrpClient("Pair-Setup", "3939", ByteArray(256) { 0x11 })
        assertEquals(v["A"]!!.toHex(), client.publicA.toMinBytes().toHex())
        val m1 = client.processChallenge(v["salt"]!!, v["B"]!!)
        assertEquals(v["K"]!!.toHex(), client.sessionKey.toHex())
        assertEquals(v["M"]!!.toHex(), m1.toHex())
        assertTrue(client.verifyServer(v["HAMK"]!!))
    }

    @Test
    fun bplistRoundTrip() {
        val src = linkedMapOf<String, Any?>(
            "deviceID" to "AA:BB:CC:DD:EE:FF",
            "port" to 7000L,
            "big" to 0x1_0000_0000L,
            "flag" to true,
            "ratio" to 0.5,
            "key" to byteArrayOf(1, 2, 3),
            "unicode" to "Wohnzimmer – Küche",
            "streams" to listOf(mapOf("type" to 96L, "ct" to 2L)),
        )
        @Suppress("UNCHECKED_CAST")
        val back = Bplist.decode(Bplist.encode(src)) as Map<String, Any?>
        assertEquals("AA:BB:CC:DD:EE:FF", back["deviceID"])
        assertEquals(7000L, back["port"])
        assertEquals(0x1_0000_0000L, back["big"])
        assertEquals(true, back["flag"])
        assertEquals(0.5, back["ratio"])
        assertArrayEquals(byteArrayOf(1, 2, 3), back["key"] as ByteArray)
        assertEquals("Wohnzimmer – Küche", back["unicode"])
        assertEquals(96L, ((back["streams"] as List<*>)[0] as Map<*, *>)["type"])
    }

    @Test
    fun tlvFragmentsLongValues() {
        val pk = ByteArray(384) { it.toByte() }
        val enc = Tlv8.encode(Tlv8.STATE to Tlv8.byte(3), Tlv8.PUBLIC_KEY to pk, Tlv8.PROOF to ByteArray(64) { 7 })
        // 384 bytes -> fragments of 255 + 129
        assertEquals(3 + (2 + 255) + (2 + 129) + (2 + 64), enc.size)
        val dec = Tlv8.decode(enc)
        assertArrayEquals(pk, dec[Tlv8.PUBLIC_KEY])
        assertEquals(3, dec[Tlv8.STATE]!![0].toInt())
        assertEquals(64, dec[Tlv8.PROOF]!!.size)
    }

    @Test
    fun chachaRoundTripWithLabelNonce() {
        val key = ByteArray(32) { 9 }
        val sealed = Crypto.chachaSeal(key, Crypto.labelNonce("PS-Msg05"), "hello".toByteArray())
        assertEquals(5 + 16, sealed.size)
        assertEquals("hello", String(Crypto.chachaOpen(key, Crypto.labelNonce("PS-Msg05"), sealed)))
    }

    @Test
    fun resamplerProducesExpectedRate() {
        val r = Resampler(44100, 48000)
        var outFrames = 0
        repeat(100) { outFrames += r.process(ShortArray(2048) { 1000 }, 2048).size / 2 }
        val expected = 100 * 1024 * 48000.0 / 44100
        assertTrue("got $outFrames, want ~$expected", kotlin.math.abs(outFrames - expected) < 3)
    }

    /**
     * Writes our verbatim ALAC packets into a CAF file so an independent decoder (ffmpeg) can
     * check them: see scripts/verify-alac.sh.
     */
    @Test
    fun alacPacketsWrittenAsCaf() {
        val packets = 200
        val pcm = ShortArray(Alac.FRAMES_PER_PACKET * 2 * packets)
        for (i in 0 until pcm.size / 2) {
            pcm[i * 2] = (sin(2 * PI * 440 * i / 44100) * 12000).toInt().toShort()
            pcm[i * 2 + 1] = (sin(2 * PI * 660 * i / 44100) * 9000).toInt().toShort()
        }
        val encoded = (0 until packets).map { Alac.encodeVerbatim(pcm, it * Alac.FRAMES_PER_PACKET * 2, Alac.FRAMES_PER_PACKET) }
        assertTrue(encoded.all { it.size == 1412 })

        val dir = File("build/alac-test").apply { mkdirs() }
        File(dir, "expected.raw").writeBytes(ByteArray(pcm.size * 2).also { b ->
            pcm.forEachIndexed { i, s -> b[i * 2] = s.toByte(); b[i * 2 + 1] = (s.toInt() shr 8).toByte() }
        })
        File(dir, "packets.caf").writeBytes(caf(encoded))
    }

    private fun caf(packets: List<ByteArray>): ByteArray {
        val out = ByteArrayOutputStream()
        val d = DataOutputStream(out)
        d.writeBytes("caff"); d.writeShort(1); d.writeShort(0)
        // desc
        d.writeBytes("desc"); d.writeLong(32)
        d.writeDouble(44100.0); d.writeBytes("alac"); d.writeInt(0); d.writeInt(0)
        d.writeInt(Alac.FRAMES_PER_PACKET); d.writeInt(2); d.writeInt(0)
        // kuki: ALACSpecificConfig
        d.writeBytes("kuki"); d.writeLong(24)
        d.writeInt(Alac.FRAMES_PER_PACKET); d.writeByte(0); d.writeByte(16)
        d.writeByte(40); d.writeByte(10); d.writeByte(14); d.writeByte(2)
        d.writeShort(255); d.writeInt(0); d.writeInt(0); d.writeInt(44100)
        // pakt
        val table = ByteArrayOutputStream()
        for (p in packets) {
            var v = p.size
            val bytes = ArrayList<Int>()
            do { bytes.add(0, v and 0x7F); v = v ushr 7 } while (v != 0)
            for ((i, b) in bytes.withIndex()) table.write(if (i < bytes.size - 1) b or 0x80 else b)
        }
        d.writeBytes("pakt"); d.writeLong(24L + table.size())
        d.writeLong(packets.size.toLong()); d.writeLong(packets.size.toLong() * Alac.FRAMES_PER_PACKET)
        d.writeInt(0); d.writeInt(0)
        d.write(table.toByteArray())
        // data
        val total = packets.sumOf { it.size }
        d.writeBytes("data"); d.writeLong(4L + total); d.writeInt(1)
        packets.forEach { d.write(it) }
        return out.toByteArray()
    }
}
